// Generates the Phosphor Bold sprite, search catalog and full-set demo markup
// for the icon picker. Run with `npm run icons` after changing the
// @phosphor-icons/core version.
import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { join } from 'node:path';
import { icons } from '@phosphor-icons/core';

const coreRoot = 'node_modules/@phosphor-icons/core';
const corePackage = join(coreRoot, 'package.json');
const { version } = JSON.parse(await readFile(corePackage, 'utf8'));
const outDir = 'public/icons';
const spriteHref = '/icons/phosphor-bold.svg';

const escape = (value) => String(value).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const sentence = (value) => value.charAt(0).toUpperCase() + value.slice(1);
const iconLabel = (name) => sentence(name.replace(/-/g, ' '));
const cleanTags = (tags) => tags.filter((tag) => !/^\*.*\*$/.test(tag));

const sorted = [...icons].sort((a, b) => a.name.localeCompare(b.name));

const symbols = [];
for (const icon of sorted) {
  const raw = await readFile(join(coreRoot, 'assets/bold', `${icon.name}-bold.svg`), 'utf8');
  const inner = raw.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  symbols.push(`<symbol id="${icon.name}" viewBox="0 0 256 256">${inner}</symbol>`);
}

await mkdir(outDir, { recursive: true });
await writeFile(join(outDir, 'phosphor-bold.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg"><!-- Generated from @phosphor-icons/core@${version} by tools/build-phosphor-icons.mjs; do not edit. -->\n${symbols.join('\n')}\n</svg>\n`);

const catalog = sorted.map((icon) => ({ name: icon.name, category: icon.figma_category, tags: cleanTags(icon.tags) }));
await writeFile(join(outDir, 'phosphor-catalog.json'), `${JSON.stringify({ version, icons: catalog })}\n`);
await copyFile(join(coreRoot, 'LICENSE'), join(outDir, 'LICENSE'));

// Full-set demo markup. Applications render the same structure on the server.
const groups = new Map();
for (const icon of catalog) {
  if (!groups.has(icon.category)) groups.set(icon.category, []);
  groups.get(icon.category).push(icon);
}
const tile = (icon) => {
  const label = iconLabel(icon.name);
  return `<label class="icon-picker-tile" title="${escape(label)}" data-tags="${escape(icon.tags.join(' '))}"><input type="radio" name="icon" value="${icon.name}" class="visually-hidden"><svg class="icon" aria-hidden="true" focusable="false" fill="currentColor"><use href="${spriteHref}#${icon.name}"/></svg><span class="visually-hidden">${escape(label)}</span></label>`;
};
const sections = [...groups.keys()].sort().map((category, index) => {
  const id = `all-icons-section-${index}`;
  return `<section class="icon-picker-section" aria-labelledby="${id}"><h3 class="icon-picker-section-heading" id="${id}">${escape(sentence(category))}</h3><div class="icon-picker-grid">${groups.get(category).map(tile).join('')}</div></section>`;
});
await writeFile('public/manual/_includes/icon-picker-all.html',
  `<!-- Generated by tools/build-phosphor-icons.mjs; do not edit. -->\n${sections.join('\n')}\n`);

console.log(`Wrote ${catalog.length} icons from @phosphor-icons/core@${version}.`);
